            ADD CONSTRAINT ck_eventos_categoria
            CHECK (categoria IN ('geral', 'empreendedores'));
    END IF;
END
$$;

-- Cadastros antigos que já recebiam notícias contam como opt-in confirmado.
-- Quem já tem origem preenchida não é regravado.
UPDATE congregados
SET opt_in_status = 'confirmado',
    opt_in_origem = 'cadastro_anterior',
    consentimento_em = COALESCE(consentimento_em, data_cadastro)
WHERE recebe_noticias IS TRUE
  AND anonimizado IS FALSE
  AND opt_in_status = 'pendente'
  AND opt_in_origem = '';

