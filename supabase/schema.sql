DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_congregados_opt_in'
    ) THEN
        ALTER TABLE congregados
            ADD CONSTRAINT ck_congregados_opt_in
            CHECK (opt_in_status IN ('pendente', 'confirmado', 'revogado'));
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_congregados_status_envio'
    ) THEN
        ALTER TABLE congregados
            ADD CONSTRAINT ck_congregados_status_envio
            CHECK (status_envio IN ('nunca_enviado', 'preparado', 'enviado', 'falha', 'opt_out'));
    END IF;
