-- Bucket público das imagens. O backend envia com a SUPABASE_SERVICE_KEY.
-- Quem visita o site só consegue ler. Não há política de upload para a chave anônima.
INSERT INTO storage.buckets (id, name, public)
VALUES ('midia', 'midia', TRUE)
ON CONFLICT (id) DO NOTHING;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_policies
        WHERE schemaname = 'storage'
          AND tablename = 'objects'
          AND policyname = 'midia_leitura_publica'
    ) THEN
        CREATE POLICY midia_leitura_publica
            ON storage.objects
            FOR SELECT
            USING (bucket_id = 'midia');
    END IF;
END
$$;

