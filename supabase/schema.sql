-- O Flask conecta como postgres e não é barrado pelo RLS.
-- A chave anônima não lê estas tabelas, porque não há política de acesso.

CREATE TABLE IF NOT EXISTS subsedes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    endereco TEXT NOT NULL DEFAULT '',
    bairro TEXT NOT NULL DEFAULT '',
    cidade TEXT NOT NULL,
    uf TEXT NOT NULL,
    cep TEXT NOT NULL DEFAULT '',
    telefone TEXT NOT NULL DEFAULT '',
    whatsapp TEXT NOT NULL DEFAULT '',
    email TEXT NOT NULL DEFAULT '',
    instagram_url TEXT NOT NULL DEFAULT '',
    pastor_responsavel TEXT NOT NULL DEFAULT '',
    horarios_culto TEXT NOT NULL DEFAULT '',
    mapa_url TEXT NOT NULL DEFAULT '',
    imagem_url TEXT NOT NULL DEFAULT '',
    eh_sede BOOLEAN NOT NULL DEFAULT FALSE,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    ordem INTEGER NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Só uma subsede pode ser a sede.
CREATE UNIQUE INDEX IF NOT EXISTS idx_subsedes_uma_sede
    ON subsedes (eh_sede)
    WHERE eh_sede IS TRUE;

CREATE TABLE IF NOT EXISTS congregados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    email TEXT NOT NULL,
    whatsapp TEXT NOT NULL,
    subsede_id INTEGER REFERENCES subsedes (id) ON DELETE SET NULL,
    recebe_noticias BOOLEAN NOT NULL DEFAULT TRUE,
    token_descadastro TEXT NOT NULL DEFAULT gen_random_uuid()::text UNIQUE,
    data_cadastro TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- E-mail único sem diferenciar maiúsculas.
CREATE UNIQUE INDEX IF NOT EXISTS idx_congregados_email_lower
    ON congregados (lower(email));

CREATE INDEX IF NOT EXISTS idx_congregados_subsede_id
    ON congregados (subsede_id);

CREATE TABLE IF NOT EXISTS campanhas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    meta NUMERIC(12, 2) NOT NULL DEFAULT 0,
    arrecadado NUMERIC(12, 2) NOT NULL DEFAULT 0,
    unidade TEXT NOT NULL DEFAULT 'R$',
    status TEXT NOT NULL DEFAULT 'ativa',
    imagem_url TEXT NOT NULL DEFAULT '',
    data_inicio DATE,
    data_fim DATE,
    subsede_id INTEGER REFERENCES subsedes (id) ON DELETE SET NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_campanhas_status CHECK (status IN ('ativa', 'encerrada')),
    CONSTRAINT ck_campanhas_valores CHECK (meta >= 0 AND arrecadado >= 0)
);

CREATE TABLE IF NOT EXISTS eventos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    data_evento TIMESTAMPTZ NOT NULL,
    data_fim TIMESTAMPTZ,
    dia_inteiro BOOLEAN NOT NULL DEFAULT FALSE,
    local TEXT NOT NULL DEFAULT '',
    subsede_id INTEGER REFERENCES subsedes (id) ON DELETE SET NULL,
    imagem_url TEXT NOT NULL DEFAULT '',
    status TEXT NOT NULL DEFAULT 'ativo',
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_eventos_status CHECK (status IN ('ativo', 'encerrado', 'cancelado'))
);

CREATE INDEX IF NOT EXISTS idx_eventos_data_evento
    ON eventos (data_evento);

CREATE TABLE IF NOT EXISTS informativos (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo TEXT NOT NULL,
    tipo TEXT NOT NULL,
    conteudo_url TEXT NOT NULL DEFAULT '',
    texto TEXT NOT NULL DEFAULT '',
    link_url TEXT NOT NULL DEFAULT '',
    destaque BOOLEAN NOT NULL DEFAULT FALSE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    ordem INTEGER NOT NULL DEFAULT 0,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_informativos_tipo CHECK (tipo IN ('banner', 'foto', 'video', 'aviso'))
);

CREATE TABLE IF NOT EXISTS feriados_locais (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    dia INTEGER NOT NULL,
    mes INTEGER NOT NULL,
    ano INTEGER,
    tipo TEXT NOT NULL,
    CONSTRAINT ck_feriados_locais_dia CHECK (dia >= 1 AND dia <= 31),
    CONSTRAINT ck_feriados_locais_mes CHECK (mes >= 1 AND mes <= 12),
    CONSTRAINT ck_feriados_locais_ano CHECK (ano IS NULL OR ano >= 1900),
    CONSTRAINT ck_feriados_locais_tipo CHECK (
        tipo IN ('estadual', 'municipal', 'ponto_facultativo')
    )
);

CREATE TABLE IF NOT EXISTS configuracoes (
    id INTEGER PRIMARY KEY,
    nome_igreja TEXT NOT NULL,
    slogan TEXT NOT NULL DEFAULT '',
    instagram_url TEXT NOT NULL DEFAULT '',
    instagram_usuario TEXT NOT NULL DEFAULT '',
    youtube_url TEXT NOT NULL DEFAULT '',
    facebook_url TEXT NOT NULL DEFAULT '',
    whatsapp TEXT NOT NULL DEFAULT '',
    email_contato TEXT NOT NULL DEFAULT '',
    endereco TEXT NOT NULL DEFAULT '',
    sobre TEXT NOT NULL DEFAULT '',
    CONSTRAINT ck_configuracoes_id CHECK (id = 1)
);

CREATE TABLE IF NOT EXISTS administradores (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    nome TEXT NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS comunicados (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canal TEXT NOT NULL,
    assunto TEXT NOT NULL DEFAULT '',
    mensagem TEXT NOT NULL DEFAULT '',
    evento_id INTEGER REFERENCES eventos (id) ON DELETE SET NULL,
    campanha_id INTEGER REFERENCES campanhas (id) ON DELETE SET NULL,
    subsede_id INTEGER REFERENCES subsedes (id) ON DELETE SET NULL,
    total_destinatarios INTEGER NOT NULL DEFAULT 0,
    total_enviados INTEGER NOT NULL DEFAULT 0,
    erro TEXT,
    enviado_por TEXT NOT NULL DEFAULT '',
    enviado_em TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_comunicados_canal CHECK (canal IN ('email', 'whatsapp'))
);

