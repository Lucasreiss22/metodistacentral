def alinhar_banco(aplicacao: Flask) -> None:
    """Aplica as colunas novas no Postgres. Nos testes não conecta."""
    if aplicacao.config.get("TESTING"):
        return
    url = aplicacao.config.get("DATABASE_URL") or ""
    if problemas_da_database_url(url):
        return
    uri = aplicacao.config.get("SQLALCHEMY_DATABASE_URI") or ""
    with aplicacao.app_context():
        try:
            if db.engine.dialect.name != "postgresql":
                return
            for comando in COMANDOS:
                db.session.execute(text(comando))
            db.session.commit()
        except Exception as erro:
            db.session.rollback()
            aplicacao.logger.error(
                "Não foi possível alinhar o banco. %s",
                mensagem_sem_senha(str(erro), url, uri),
            )
            return
        try:
            for comando in COMANDOS_EXTRAS:
                db.session.execute(text(comando))
            db.session.commit()
        except Exception as erro:
            db.session.rollback()
            aplicacao.logger.error(
                "Colunas novas gravadas. O complemento do schema falhou. %s",
                mensagem_sem_senha(str(erro), url, uri),
            )
        try:
            mensagens, codigo = garantir_super_admin(aplicacao, avisar_senha_mantida=False)
        except Exception as erro:
            db.session.rollback()
            aplicacao.logger.error(
                "Não foi possível criar o administrador master. %s",
                mensagem_sem_senha(str(erro), url, uri),
            )
            return
        for linha in mensagens:
            if codigo:
                aplicacao.logger.error(linha)
            else:
                aplicacao.logger.info(linha)


def garantir_super_admin(aplicacao: Flask, avisar_senha_mantida: bool = True) -> tuple[list[str], int]:
    """Cria ou atualiza o administrador master. A senha é gravada como hash.

    Precisa de um app context aberto. Devolve as frases do terminal e
    1 quando a senha informada não serve.
    """
    from sqlalchemy import func

    from app import EMAIL_ADMIN_INICIAL, SENHA_ADMIN_INICIAL
    from app.auth import hash_senha, validar_senha_nova
    from app.models import Administrador
    from app.utils import normalizar_email

    email = normalizar_email(aplicacao.config.get("ADMIN_EMAIL") or EMAIL_ADMIN_INICIAL)
    senha_env = aplicacao.config.get("ADMIN_SENHA") or ""
    admin = Administrador.query.filter(func.lower(Administrador.email) == email).one_or_none()
    if admin is None:
        admin = Administrador(
            email=email,
            nome="Administrador",
            ativo=True,
            ministerio="Administração",
        )
        db.session.add(admin)
    if admin.senha_hash and not senha_env:
        admin.ativo = True
        admin.eh_super_admin = True
        db.session.commit()
        if not avisar_senha_mantida:
            return [], 0
        return [
            f"Super administrador mantido: {email}",
            "A senha já existia e não foi trocada. Para trocar, preencha ADMIN_SENHA e rode de novo.",
        ], 0
    senha = senha_env or SENHA_ADMIN_INICIAL
    erro = validar_senha_nova(senha)
    if erro:
        db.session.rollback()
        return [erro], 1
    admin.nome = admin.nome or "Administrador"
    admin.ministerio = admin.ministerio or "Administração"
    admin.ativo = True
    admin.eh_super_admin = True
    admin.senha_hash = hash_senha(senha)
    db.session.commit()
    linhas = [f"Super administrador pronto: {email}"]
    if senha_env:
        linhas.append("Senha definida pela variável ADMIN_SENHA.")
    else:
        linhas.append(
            "Senha inicial: a documentada em README_ATUALIZACOES.md. "
            "Troque no painel depois do primeiro acesso."
        )
    return linhas, 0
